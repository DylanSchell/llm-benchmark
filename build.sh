#!/usr/bin/env bash
# Build scripts for llm-benchmark (Rust workspace)
# Replaces Maven-based build pipeline.

set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Canonical image name. Build, run and push all derive from this, so there is exactly one name for
# the artifact and no way to publish an image under a name you never run. Override with --image
# (or IMAGE_REPO=…) when building a fork.
DEFAULT_IMAGE_REPO="ghcr.io/dylanschell/llm-benchmark-runner"

image_repo() {
    printf '%s' "${IMAGE_REPO:-$DEFAULT_IMAGE_REPO}"
}

usage() {
    cat >&2 <<EOF
Usage: $(basename "$0") <command> [options]

Commands:
  docker-build   Build the runner Docker image (default)
  docker-push    Publish the built image to its registry (never automatic)
  docker-run     Run a command inside the runner container
  docker-verify  Check docker/ inputs against docker/runner.lock
  cargo          Pass-through to cargo
  test           Run all workspace tests
  clean          Clean build artifacts

Options:
  --arch         Platform(s) to build, comma-separated (default: host platform)
                 e.g. linux/arm64   or   linux/amd64,linux/arm64
  --tag          Image tag (default: <image>:latest)
  --image        Image repository (default: ${DEFAULT_IMAGE_REPO})

Every build tags the image twice: <image>:latest and <image>:<version>, where <version> comes from
Cargo.toml. Building never contacts a registry; publishing is the separate, explicit
docker-push verb.
EOF
    exit 1
}

# ---------------------------------------------------------------------------
# Version
#
# One number identifies the project: `llm-benchmark --version` prints it (via CARGO_PKG_VERSION),
# build.sh tags the image with it, and GitHub Releases are tagged v<version>. It lives in Cargo.toml
# because that is the only place Cargo reads it from at compile time — a separate
# docker/RUNNER_VERSION could only ever mirror it, and a mirror is one more thing to forget.
#
# docker/runner.lock records that version and the hash of the docker/ inputs at the last successful
# build, so `docker-verify` can tell you whether an input changed without the version being bumped.
# See docs/specs/runner-image.md for the bump policy.
#
# runner.lock and the docs are excluded from the hash on purpose: it describes the inputs that
# determine image content, so bumping the version is the acknowledgement of a change to them, and a
# README edit should not demand a new image.
# ---------------------------------------------------------------------------

runner_version() {
    local file="${SCRIPT_DIR}/Cargo.toml"
    local version
    version="$(awk '
        /^\[workspace\.package\]/ { section = 1; next }
        /^\[/                   { section = 0 }
        section && /^version[[:space:]]*=[[:space:]]*"/ {
            gsub(/^[^"]*"/, ""); gsub(/".*$/, ""); print; exit
        }
    ' "$file")"
    if [[ -z "$version" ]]; then
        echo "error: no version found under [workspace.package] in ${file}" >&2
        return 1
    fi
    printf '%s\n' "$version"
}

# Replaces the version in place, scoped to [workspace.package] so a dependency's version cannot be
# matched by accident. Callers must refresh Cargo.lock afterwards — it records workspace member
# versions, and CI builds with --locked.
set_runner_version() {
    local new="$1" file="${SCRIPT_DIR}/Cargo.toml" tmp
    tmp="$(mktemp)"
    if ! awk -v new="$new" '
        /^\[workspace\.package\]/ { section = 1; print; next }
        /^\[/                   { section = 0 }
        {
            if (section && /^version[[:space:]]*=[[:space:]]*"/) {
                print "version = \"" new "\""
                replaced = 1
            } else {
                print
            }
        }
        END { if (!replaced) exit 1 }
    ' "$file" > "$tmp"; then
        rm -f "$tmp"
        echo "error: no version line under [workspace.package] in ${file}" >&2
        return 1
    fi
    mv "$tmp" "$file"
}

hash_file() {
    if command -v shasum >/dev/null 2>&1; then
        shasum -a 256 "$1" | awk '{print $1}'
    else
        sha256sum "$1" | awk '{print $1}'
    fi
}

docker_input_hash() {
    local dir="${SCRIPT_DIR}/docker"
    local hasher="sha256sum"
    if command -v shasum >/dev/null 2>&1; then
        hasher="shasum -a 256"
    fi
    (
        cd "$dir" || exit 1
        find . -type f ! -name 'runner.lock' ! -name '*.md' \
            | LC_ALL=C sort \
            | while IFS= read -r f; do
                  printf '%s  %s\n' "$(hash_file "$f")" "$f"
              done
    ) | $hasher | awk '{print $1}'
}

write_runner_lock() {
    local version="$1" hash="$2" platforms="${3:-}"
    cat > "${SCRIPT_DIR}/docker/runner.lock" <<EOF
# Generated by ./build.sh docker-build. Do not edit by hand.
# inputHash covers every build input under docker/, excluding this file and *.md.
# platforms is not a build input — it records what the last build targeted, so docker-push can
# report (and check) the platform set it is about to publish.
version=${version}
inputHash=${hash}
platforms=${platforms}
EOF
}

docker_verify() {
    local dir="${SCRIPT_DIR}/docker"
    local lock_file="${dir}/runner.lock"
    local version hash lock_version lock_hash rc=0

    version="$(runner_version)"
    hash="$(docker_input_hash)"
    load_agents

    if [[ ! -f "$lock_file" ]]; then
        echo "FAIL: ${lock_file} is missing — run ./build.sh docker-build" >&2
        return 1
    fi

    lock_version="$(sed -n 's/^version=//p' "$lock_file")"
    lock_hash="$(sed -n 's/^inputHash=//p' "$lock_file")"

    if [[ "$hash" != "$lock_hash" ]]; then
        echo "FAIL: docker/ inputs changed since the last recorded build." >&2
        echo "        recorded ${lock_hash} " >&2
        echo "        now      ${hash} " >&2
        echo "      Bump the version in Cargo.toml, then rebuild: ./build.sh docker-build" >&2
        rc=1
    fi

    if [[ "$version" != "$lock_version" ]]; then
        echo "FAIL: Cargo.toml is at ${version} but runner.lock records ${lock_version}." >&2
        echo "      Rebuild to refresh the lock: ./build.sh docker-build" >&2
        rc=1
    fi

    # Also lint the pins, so an unpinned install cannot slip in unnoticed.
    if [[ -x "${SCRIPT_DIR}/docker/pin-agents.sh" ]]; then
        if ! "${SCRIPT_DIR}/docker/pin-agents.sh" --check; then
            rc=1
        fi
    fi

    if (( rc == 0 )); then
        echo "ok: runner image v${version} [$(agents_list)] matches docker/ inputs (${hash:0:12}…)"
    fi
    return $rc
}

# External version pins live in docker/pins.env. The Dockerfile's ARGs deliberately have no
# defaults, so every one of them has to be supplied here — a bare `docker build` fails loudly
# rather than silently producing an unpinned image.
load_pins() {
    local pins="${SCRIPT_DIR}/docker/pins.env"
    if [[ ! -f "$pins" ]]; then
        echo "error: ${pins} not found" >&2
        exit 1
    fi
    # shellcheck disable=SC1090
    set -a
    . "$pins"
    set +a
}

# Optional-agent selection lives in docker/agents.env so it is part of docker_input_hash: two
# images built from the same inputs are then guaranteed to contain the same agents, which a bare
# --build-arg could not promise. See docker/README.md for why Claude Code is off by default.
load_agents() {
    local file="${SCRIPT_DIR}/docker/agents.env"
    if [[ ! -f "$file" ]]; then
        echo "error: ${file} not found" >&2
        exit 1
    fi
    # shellcheck disable=SC1090
    set -a
    . "$file"
    set +a

    case "${INSTALL_CLAUDE:-}" in
        0|1) ;;
        *) echo "error: INSTALL_CLAUDE must be 0 or 1 in ${file}" >&2; exit 1 ;;
    esac
}

# Comma-separated agents the image contains, for the OCI label and the in-image marker.
agents_list() {
    if [[ "${INSTALL_CLAUDE}" == "1" ]]; then
        printf 'claude,pi'
    else
        printf 'pi'
    fi
}

# Build args are derived from this name list, so adding a pin to pins.env plus the Dockerfile
# is enough — this script needs no edit.
PIN_NAMES=(
    BASE_IMAGE
    GO_VERSION FD_VERSION NODE_MAJOR RUST_VERSION UV_VERSION
    GRADLE_VERSION GRADLE_SHA256
    CLAUDE_CODE_VERSION PI_CODING_AGENT_VERSION PI_SHA256_X64 PI_SHA256_ARM64
    PI_CAVEMAN_VERSION SUPI_BASH_TIMEOUT_VERSION
    JEST_VERSION BABEL_CORE_VERSION BABEL_PRESET_ENV_VERSION
    EXERCISM_BABEL_PRESET_VERSION EXERCISM_ESLINT_CONFIG_VERSION
    TYPES_JEST_VERSION TYPES_NODE_VERSION BABEL_JEST_VERSION
    CORE_JS_VERSION ESLINT_VERSION
)

# --arch accepts a comma-separated platform list. Validate it here so a typo fails loudly rather
# than building one platform while you believe you built more. Only these two are accepted because
# the Dockerfile's Go, fd and pi steps reject anything else — failing here just fails earlier and
# with a clearer message.
validate_platforms() {
    local list="$1" p
    local -a plats
    IFS=',' read -r -a plats <<< "$list"
    for p in "${plats[@]}"; do
        case "$p" in
            linux/amd64|linux/arm64) ;;
            *)
                echo "error: unsupported platform '${p}' in --arch." >&2
                echo "       This image builds for linux/amd64 and linux/arm64 only." >&2
                return 1
                ;;
        esac
    done
}

docker_build() {
    local repo
    repo="$(image_repo)"
    local tag="${TAG:-${repo}:latest}"
    local arch="${ARCH:-}"
    local platforms
    local platform_args=()
    if [[ -n "$arch" ]]; then
        validate_platforms "$arch" || return 1
        platforms="$arch"
        platform_args=(--platform "$platforms")
        echo "Building Docker image ${tag} for ${platforms}..." >&2
        if [[ "$platforms" == *,* ]]; then
            echo "        multi-platform: the result is an OCI index in the local image store" >&2
        fi
    else
        platforms="$(docker version --format '{{.Server.Os}}/{{.Server.Arch}}' 2>/dev/null || true)"
        echo "Building Docker image ${tag} (host platform${platforms:+: ${platforms}})..." >&2
    fi

    load_pins
    load_agents
    local version agents
    version="$(runner_version)"
    agents="$(agents_list)"
    local version_tag="${repo}:${version}"

    local -a build_args=()
    local name
    for name in "${PIN_NAMES[@]}"; do
        build_args+=(--build-arg "${name}=${!name}")
    done
    build_args+=(--build-arg "RUNNER_VERSION=${version}")
    build_args+=(--build-arg "INSTALL_CLAUDE=${INSTALL_CLAUDE}")
    build_args+=(--build-arg "AGENTS=${agents}")

    echo "Pinned: go=${GO_VERSION} rust=${RUST_VERSION} uv=${UV_VERSION} gradle=${GRADLE_VERSION}" >&2
    if [[ "${INSTALL_CLAUDE}" == "1" ]]; then
        echo "        agents=${agents} (claude-code=${CLAUDE_CODE_VERSION}, pi=${PI_CODING_AGENT_VERSION})" >&2
    else
        echo "        agents=${agents} (pi=${PI_CODING_AGENT_VERSION}; Claude Code excluded)" >&2
    fi
    echo "Version: ${version} (also tagged ${version_tag})" >&2

    # --provenance=false: buildx otherwise attaches a provenance attestation whose payload embeds
    # the build timestamp, so the published OCI *index* digest changes on every rebuild even when
    # every layer and the image config are identical. The image content is reproducible either way,
    # but without this a re-push rewrites a versioned tag to a new digest, which breaks anyone
    # pinning by digest and makes :<VERSION> mutable. See docker/README.md.
    docker buildx build \
        "${platform_args[@]}" \
        "${build_args[@]}" \
        --provenance=false \
        --tag "${tag}" \
        --tag "${version_tag}" \
        -f docker/Dockerfile.runner.debian \
        "${SCRIPT_DIR}/docker"

    # Record the inputs this image was built from. Only reached if the build succeeded.
    write_runner_lock "$version" "$(docker_input_hash)" "$platforms"
    echo "Recorded ${version} (${platforms}) in docker/runner.lock" >&2
}

# Publishing is a separate verb on purpose: building an image and shipping gigabytes to a registry
# are different decisions, and neither an accidental push nor a published image we have no right to
# distribute is recoverable. So this never runs as part of a build.
docker_push() {
    local repo version host
    repo="$(image_repo)"
    version="$(runner_version)"

    load_agents
    # Claude Code carries no redistribution right (see docker/README.md), so an image containing it
    # must not be published anywhere, private or public.
    if [[ "${INSTALL_CLAUDE}" == "1" && "${PUSH_UNLICENSED:-0}" != "1" ]]; then
        echo "FAIL: this image packages Claude Code, which Anthropic licenses \"all rights reserved\"" >&2
        echo "      with no redistribution grant, so it must not be pushed to a registry." >&2
        echo "      Set INSTALL_CLAUDE=0 in docker/agents.env and rebuild, or set PUSH_UNLICENSED=1" >&2
        echo "      to override deliberately." >&2
        return 1
    fi

    # The tag has to describe an image we can reproduce, so check the inputs before they leave.
    docker_verify || return 1

    if ! docker image inspect "${repo}:${version}" >/dev/null 2>&1; then
        echo "FAIL: ${repo}:${version} is not present locally — build it first:" >&2
        echo "      ./build.sh docker-build" >&2
        return 1
    fi

    host="${repo%%/*}"

    # What is about to be published, and what is already there. The failure mode this exists to
    # prevent: a later single-platform rebuild quietly replacing an already-published
    # multi-platform tag, which would be invisible without this.
    local platforms mt local_kind remote_count
    platforms="$(sed -n 's/^platforms=//p' "${SCRIPT_DIR}/docker/runner.lock" 2>/dev/null)"
    mt="$(docker image inspect "${repo}:${version}" --format '{{.Descriptor.mediaType}}' 2>/dev/null || true)"
    if [[ "$mt" == *index* || "$mt" == *manifest.list* ]]; then
        local_kind="OCI index (multi-platform)"
    else
        local_kind="single-platform manifest"
    fi
    remote_count="$(docker manifest inspect "${repo}:${version}" 2>/dev/null \
        | grep -c '"architecture"' || true)"

    echo "Publishing ${repo}:${version} and ${repo}:latest" >&2
    echo "        platforms : ${platforms:-unknown} — ${local_kind}" >&2
    if [[ "${remote_count:-0}" =~ ^[0-9]+$ ]] && (( remote_count > 1 )) \
       && [[ "$local_kind" != "OCI index (multi-platform)" ]]; then
        echo "        WARNING   : the registry already serves ${remote_count} platforms for this tag, and" >&2
        echo "                    this push would narrow it to one. Rebuild for all platforms with:" >&2
        echo "                    ./build.sh docker-build --arch linux/amd64,linux/arm64" >&2
    fi
    if ! docker push "${repo}:${version}" || ! docker push "${repo}:latest"; then
        echo "Push failed. If the registry rejected the credentials, authenticate first:" >&2
        echo "    docker login ${host}" >&2
        return 1
    fi
    echo "Published ${repo}:${version} and ${repo}:latest" >&2
}

docker_run() {
    local repo
    repo="$(image_repo)"
    local tag="${TAG:-${repo}:latest}"
    docker run --rm -it "${tag}" "$@"
}

cargo_cmd() {
    cargo "$@"
}

test_all() {
    cargo test --workspace
}

clean_artifacts() {
    rm -rf target
    echo "Cleaned build artifacts." >&2
}

# Only dispatch when executed directly, so the functions above can be sourced by tests.
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
    # Parse options (can appear before or after the command)
    ARCH=""
    TAG=""
    IMAGE_REPO=""
    COMMAND=""
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --arch)  ARCH="$2";       shift 2 ;;
            --tag)   TAG="$2";        shift 2 ;;
            --image) IMAGE_REPO="$2";  shift 2 ;;
            docker-build|build|docker-push|push|docker-run|run|docker-verify|verify|cargo|test|clean)
                COMMAND="$1"
                shift
                ;;
            *)      break ;;
        esac
    done

    case "$COMMAND" in
        docker-build|build)   docker_build ;;
        docker-push|push)     docker_push ;;
        docker-run|run)       docker_run "$@" ;;
        docker-verify|verify) docker_verify ;;
        cargo)                cargo_cmd "$@" ;;
        test)                 test_all ;;
        clean)                clean_artifacts ;;
        *)                    usage ;;
    esac
fi
